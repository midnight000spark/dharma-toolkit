/// Доменная модель особого календарного дня (FR-CAL-1).
///
/// Чистая доменная сущность: не Drift-таблица, не завязана на слой данных.
/// Персистентность (если понадобится) — отдельная таблица и маппинг,
/// см. решение блока 5 пакета 5b.
///
/// **Где живёт (D-37, пакет 6.1):** `lib/core/calendar/` — общий контракт, а
/// не принадлежность фичи календаря. Причина: лента событий (`features/events`)
/// обязана читать особые дни, а импорт feature→feature запрещён (принцип №1,
/// guard-тест); копия модели в событиях дала бы второй источник истины
/// (уроки B-4/R-20). Ядро при этом о фичах не знает — здесь только модель.
library;

/// Тип особого дня.
///
/// Замечание об extensibility: новый тип = значение enum + обработчики;
/// праздники традиций, не входящих в MVP-скоуп (D-23), попадают в [festival],
/// специальные типы при необходимости добавляются — ядро о них не узнаёт.
enum SpecialDayType {
  /// Упосатха — день обета по фазе Луны (Тхеравада, FR-CAL-2).
  uposatha,

  /// 10-й день тибетского месяца (полусамоцветный день, FR-CAL-3).
  tibetan10,

  /// 25-й день тибетского месяца (полусамоцветный день, FR-CAL-3).
  tibetan25,

  /// Праздник (Лосар, Сага Дава и т.п.; для любой традиции).
  festival,
}

/// Особый день: конкретная григорианская дата с типом и человекочитаемым
/// описанием. Имя и описание — данные традиции (русский — единственный
/// язык продукта, D-28), а не ключи локализации: экраны Этапа 8 могут
/// переопределить вывод, домен остаётся источником канонических имён.
class SpecialDay {
  /// Календарный день, нормализованный в **UTC-полночь** (`DateTime.utc`),
  /// а не момент времени (W13): поля `year/month/day` — истина, `hour == 0`
  /// гарантирован в любой зоне. Локальная полночь не годится: в зонах, где
  /// переход часов происходит в 00:00 (например, Santiago/Havana), её не
  /// существует и Dart разворачивает её в 01:00 — день зависел бы от зоны
  /// устройства, а ключи дедупликации и сравнения `==` расходились бы.
  /// Потребители сравнивают дни **по полям**, не инстантами.
  final DateTime date;

  /// Тип особого дня.
  final SpecialDayType type;

  /// Отображаемое имя («Упосатха (полнолуние)», «Лосар — тибетский Новый год»).
  final String name;

  /// Пояснение для детали дня; может быть пустым.
  final String description;

  const SpecialDay({
    required this.date,
    required this.type,
    required this.name,
    this.description = '',
  });

  @override
  bool operator ==(Object other) =>
      other is SpecialDay &&
      other.date == date &&
      other.type == type &&
      other.name == name &&
      other.description == description;

  @override
  int get hashCode => Object.hash(date, type, name, description);

  @override
  String toString() =>
      'SpecialDay(${date.toIso8601String().substring(0, 10)} $type $name)';
}
