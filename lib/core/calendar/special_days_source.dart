/// Порт «источник особых дней» (D-37, пакет 6.1) — мост между фичей событий
/// и фичей календаря, объявленный в ядре.
///
/// **Зачем:** `features/events` обязана видеть и особые дни календаря, и даты,
/// которые вычисляет движок календаря (правило `tibetan` пака событий, D-35).
/// Импорт feature→feature при этом запрещён (принцип №1, guard-тест R-10), а
/// второе объявление контракта — второй источник истины. Единственное легальное
/// направление — общий контракт в `lib/core/calendar/`.
///
/// **Форма (паттерн `appDatabaseProvider`, D-22):** провайдер-порт с
/// неуспешным дефолтом. Без явной привязки он падает [StateError]'ом, а не
/// молча тянет синглтон из реестра (service locator запрещён, D-4/D-22):
/// молчаливая подмена источника дней — ровно тот класс дефектов, который
/// закрывали R-11/R-13/R-20.
///
/// **Привязка:** composition root переопределяет порт источником активной
/// традиции (адаптер `CalendarSpecialDaysSource` в фиче календаря); биндинг в
/// `main.dart` — пакет 6.2. До него порт остаётся непривязанным по умолчанию.
///
/// **Контракт значения:**
///  * `null` — активного пресета нет либо для его тега календаря в сборке нет
///    (честная деградация 4.1: «календаря для этой традиции пока нет», не
///    пустой список и не чужой календарь);
///  * исключение [StateError] — порт не привязан вовсе (ошибка композиции,
///    а не пользовательская ситуация).
library;

import 'package:flutter_riverpod/flutter_riverpod.dart';

import 'special_day.dart';

/// Особые дни активной традиции + возможности движка её календаря.
///
/// Отделён от [CalendarProvider] (D-37 выносит контракт календаря как есть):
/// провайдер отвечает на вопрос «какие особые дни в диапазоне», источник —
/// ещё и на вопрос «где выпадает день M/D тибетского месяца», который нужен
/// правилу `tibetan` пака событий (D-35). Реализации источников живут в
/// `features/calendar`; ядро о них не знает.
abstract class SpecialDaysSource {
  /// Тег традиции активного пресета (принцип №3) — атрибуция в ленте и
  /// отбор паков по тегу. Берётся из данных, не из литерала в коде (B-4).
  String get traditionTag;

  /// Особые дни календаря в диапазоне [from]..[to] включительно (FR-CAL-1);
  /// контракт — как у [CalendarProvider.getSpecialDays].
  List<SpecialDay> getSpecialDays(DateTime from, DateTime to);

  /// Даты диапазона [from]..[to], на которые выпадает день [day] месяца
  /// [month] тибетского календаря (правило `dateRule.kind == tibetan`, D-35).
  ///
  /// **`null` — календарь традиции тибетских дат не знает** (например,
  /// тхеравада с лунными упосатхами): правило неразрешимо для этой традиции.
  /// Это честный отказ, отличный от пустого списка «такая дата в окне не
  /// встречается» — потребитель обязан показать разные состояния (SCR-12).
  ///
  /// В год с удвоенным месяцем день M/D существует дважды — возвращаются обе
  /// даты (математика честнее выбора одной); селекция «только первая» —
  /// вопрос следующей версии схемы пака, не молчаливое правило v1.
  List<DateTime>? resolveTibetanMonthDay({
    required int month,
    required int day,
    required DateTime from,
    required DateTime to,
  });
}

/// Источник особых дней активной традиции (или `null`, если календаря для
/// активного пресета нет). Переопределяется в composition root (пакет 6.2).
final specialDaysSourceProvider = Provider<SpecialDaysSource?>(
  (ref) => throw StateError(
    'specialDaysSourceProvider не привязан: composition root обязан '
    'переопределить порт источником особых дней активного пресета (D-37)',
  ),
);

/// Источник особых дней **по явному тегу** традиции (D-37, пакет 6.2).
///
/// Второй вход в тот же порт нужен перепланированию уведомлений: событие смены
/// пресета приходит раньше, чем реактивная проводка UI обновит
/// [specialDaysSourceProvider] (пресет → тег → источник), а план обязан
/// строиться по традиции, которая активна **сейчас**, — иначе напоминания
/// поставятся по покинутой традиции. Тег берётся из актуального пресета, и по
/// нему запрашивается источник — без гонки с потоковым слоем.
///
/// **Контракт значения тот же:** `null` — календаря для такого тега в сборке
/// нет; [StateError] — порт не привязан вовсе (ошибка композиции).
final specialDaysSourceForTagProvider =
    Provider.family<SpecialDaysSource?, String>(
  (ref, traditionTag) => throw StateError(
    'specialDaysSourceForTagProvider не привязан: composition root обязан '
    'переопределить порт источником особых дней по тегу традиции (D-37)',
  ),
);
