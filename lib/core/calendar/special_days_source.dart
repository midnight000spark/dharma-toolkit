/// Порт «источник особых дней» (D-37, пакет 6.1) — мост между фичей событий
/// и фичей календаря, объявленный в ядре.
///
/// **Зачем:** `features/events` обязана видеть особые дни календаря, но
/// импорт feature→feature запрещён (принцип №1, guard-тест R-10), а второе
/// объявление контракта — второй источник истины. Единственное легальное
/// направление — общий контракт в `lib/core/calendar/`.
///
/// **Форма (паттерн `appDatabaseProvider`, D-22):** провайдер-порт с
/// неуспешным дефолтом. Без явной привязки он падает [StateError]'ом, а не
/// молча тянет синглтон из реестра (service locator запрещён, D-4/D-22):
/// молчаливая подмена источника дней — ровно тот класс дефектов, который
/// закрывали R-11/R-13/R-20.
///
/// **Привязка:** `main.dart` (composition root) переопределяет порт
/// `overrideWithValue`'ом календарной реализации активного пресета; сам ядро
/// о конкретных традициях не знает. Биндинг в `main.dart` — пакет 6.2:
/// до него порт остаётся непривязанным по умолчанию.
///
/// **Контракт значения:**
///  * `null` — активного пресета нет либо для его тега календаря в сборке
///    нет (честная деградация 4.1: «календаря для этой традиции пока нет»,
///    не пустой список и не чужой календарь);
///  * исключение [StateError] — порт не привязан вовсе (ошибка композиции,
///    а не пользовательская ситуация).
library;

import 'package:flutter_riverpod/flutter_riverpod.dart';

import 'calendar_provider.dart';

/// Активный источник особых дней (или `null`, если календаря для активного
/// пресета нет). Переопределяется в `main.dart` (пакет 6.2).
final specialDaysSourceProvider = Provider<CalendarProvider?>(
  (ref) => throw StateError(
    'specialDaysSourceProvider не привязан: main.dart обязан переопределить '
    'порт календарной реализацией активного пресета (D-37)',
  ),
);
