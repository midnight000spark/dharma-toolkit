/// Порт «источник чтения дня» (аналог `SpecialDaysSource`, D-37; блок C 7.0).
///
/// **Зачем:** чтение дня нужно не только фиче контента — его показывает дашборд
/// (SCR-7) и экран «Чтение дня» (SCR-13), а прямой импорт feature→feature
/// запрещён (принцип №1, guard-тест R-10). Второе объявление контракта было бы
/// вторым источником истины. Единственное легальное направление — контракт в
/// `lib/core/`; типы значения — в [DailyReading].
///
/// **Форма (паттерн `appDatabaseProvider`/`specialDaysSourceProvider`, D-22):**
/// провайдер-порт с неуспешным дефолтом. Без явной привязки он падает
/// [StateError]'ом, а не молча тянет синглтон из реестра (service locator
/// запрещён, D-4/D-22). Молчаливая подмена источника чтений заглушкой — ровно
/// тот класс дефектов, который закрывали R-11/R-13/R-20.
///
/// **Контракт значения — фолбэк не ошибка:** реализация обязана вернуть **не
/// пустой** список чтений. Если контент-паков активной традиции нет или они
/// сломаны, приходит собственная формулировка приложения с честной атрибуцией
/// (FR-CNT-3): «нечего показать» — не то же самое, что «показывать нечего, и
/// экран пуст».
///
/// **Привязка:** composition root переопределяет порт реализацией фичи
/// (`DailyReadingContentSource`). Биндинга в `main.dart` в пакете 7.0 нет — он
/// появится вместе с UI чтения дня (7.1), как у порта календаря это было
/// отложено до 6.2.
library;

import 'package:flutter_riverpod/flutter_riverpod.dart';

import 'daily_reading.dart';

/// Источник чтений дня активной традиции.
abstract class ContentSource {
  /// Тег традиции, к которой относится контент (принцип №3) — значение из
  /// данных пресета, не из литерала в коде (B-4).
  String get traditionTag;

  /// Чтения дня [day] (время аргумента не значимо).
  ///
  /// **Никогда не пуст:** при недоступности контента приходит фолбэк FR-CNT-3.
  /// Привязанные к дате чтения идут первыми, ротация — второй.
  List<ContentReading> readingsFor(DateTime day);
}

/// Источник чтений активной традиции. Переопределяется в composition root.
final contentSourceProvider = Provider<ContentSource>(
  (ref) => throw StateError(
    'contentSourceProvider не привязан: composition root обязан переопределить '
    'порт источником чтений дня активного пресета (блок C 7.0)',
  ),
);
