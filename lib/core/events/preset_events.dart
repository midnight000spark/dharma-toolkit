/// События смены активного пресета (D-21, пакет 6.2).
///
/// Прежде шина была инстанцируемой, но без потребителя (D-21). Первый
/// потребитель — перепланирование напоминаний (`features/events`): смена
/// традиции меняет и календарь, и паки событий, поэтому старые уведомления
/// обязаны быть сняты, а новые поставлены (D-36 — один из трёх триггеров).
///
/// Событие объявлено в ядре: публикует его `core/config` (менеджер пресетов),
/// принимает — фича событий. Прямая зависимость между ними запрещена
/// (принцип №1), шина — легальный канал (D-5).
library;

import 'app_event.dart';

/// Активный пресет применён или снят.
class PresetChanged extends AppEvent {
  /// [traditionTag] — тег ставшей активной традиции (пустая строка — пресет
  /// снят: напоминаний не будет ни у одной традиции).
  PresetChanged({required this.traditionTag, DateTime? timestamp})
      : timestamp = timestamp ?? DateTime.now();

  /// Тег активной традиции на момент события (`preset.id`, принцип №3).
  ///
  /// Событие несёт идентификатор, а не объект пресета: потребителю нужен
  /// ответ «чья традиция стала активной», а не копия данных пресета — копия
  /// неизбежно разошлась бы с источником истины.
  final String traditionTag;

  @override
  final DateTime timestamp;

  @override
  String toString() => 'PresetChanged("$traditionTag")';
}
