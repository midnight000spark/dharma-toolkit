/// `appDatabaseProvider` в D-22: зависимость приходит извне, а не достаётся
/// синглтоном из реестра.
///
/// Файл отделён от [EventBus], чтобы класс шины не зависел от Riverpod:
/// транспорт тестируется самостоятельно (`test/core/event_bus_test.dart`),
/// без контейнера провайдеров.
library;

import 'package:flutter_riverpod/flutter_riverpod.dart';

import 'event_bus.dart';

/// Шина приложения: глобальная по умолчанию, локальная — в тестах.
