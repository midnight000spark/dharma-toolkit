import 'package:flutter/foundation.dart';

/// Текст ошибки, безопасный для показа пользователю (B-19).
///
/// Причина правки: сырые `toString()` исключений (Drift/SQL, path_provider,
/// SharedPreferences) попадали прямо в интерфейс — пользователь читал
/// внутренние детали вместо понятного объяснения.
///
/// Слой причины — само отображение ошибки, поэтому правило живёт в одной
/// функции, а не повторяется костылём в каждом новом экране: на экран уходит
/// только [message], технические [details] печатаются в лог (разработчик их
/// видит, пользователь — нет). Тот же паттерн применён в `humanErrorWidget`
/// (5.3): сообщение человеку, подробности — в консоль.
String userFacingErrorText(String message, {Object? details}) {
  if (details != null) {
    debugPrint('Ошибка (детали для разработчика): $details');
  }
  return message;
}
