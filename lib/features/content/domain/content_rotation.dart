/// Ротация чтений дня: детерминированная «случайность» (FR-CNT-1).
///
/// Требование — «чтение дня с ротацией», то есть текст обязан меняться день ото
/// дня. Но **случайность здесь не имеет права быть настоящей**: чтение дня
/// должно быть одинаковым при повторном открытии экрана в тот же день и
/// воспроизводимым в тесте (урок 5 — детерминизм проверяется без платформы;
/// `Random` без фиксированного seed дал бы «мигающий» экран и непроверяемый
/// тест). Поэтому выбор индекса — чистая функция календарного дня: для
/// пользователя это смена текста день ото дня, для теста — воспроизводимо без
/// всякого seed.
///
/// **Соседние дни не повторяются — это структурный инвариант, а не надежда.**
/// Прямое `hash(day) % size` этого не даёт: при пуле из трёх записей примерно
/// каждый третий день показывал бы вчерашний текст, а пользователь читает это
/// как «ротация сломалась». Первая редакция правила это исправляла поправкой
/// «если выпало как вчера — сдвинуть на единицу», и это было **неверно**:
/// сравнивался сырой индекс вчерашнего дня, тогда как вчерашний день сам мог
/// быть сдвинут, — при каскаде гарантия рассыпалась (тест «годовой свип»
/// покраснел). Здесь инвариант обеспечен построением:
///  * дни делятся на блоки по `size` дней, внутри блока порядок пула — свежая
///    детерминированная перестановка (Фишер–Йетс на сиде блока), поэтому
///    **внутри блока все `size` дней различны** и **каждая запись пула
///    встречается ровно раз за блок** (то есть полный обход пула);
///  * на стыке блоков порядок следующего блока при необходимости обменивается
///    по позициям 0 и 1 — первая запись блока заведомо отличается от последней
///    записи предыдущего (элементы перестановки различны), а позиция `size-1`
///    обменом не затрагивается, поэтому проверка стыка остаётся функцией
///    **соседних блоков** и не превращается в рекурсию по всей истории;
///  * пул из одной записи — вырожденный случай (повторять нечего), из двух —
///    строгое чередование (другого способа не повторяться у двух записей нет).
///
/// Хэш — FNV-1a по строковому ключу, а не `String.hashCode`: последний
/// спецификацией не обязан быть стабильным между запусками, а «чтение дня» не
/// должно зависеть от раннера.
library;

/// Выбор записи из пула по календарному дню.
abstract final class ContentRotation {
  /// Индекс записи пула размера [size] для дня [day] (время аргумента не значимо).
  ///
  /// Бросает [ArgumentError] при пустом пуле: «индекса нет» — честная ошибка
  /// вызова, а не тихий ноль, маскирующий пустоту.
  static int indexForDay(DateTime day, int size) {
    if (size <= 0) {
      throw ArgumentError.value(size, 'size', 'пул ротации пуст: индекса нет');
    }
    if (size == 1) return 0;

    final ordinal = _dayOrdinal(day);
    // Две записи обязаны чередоваться: любой другой выбор повторил бы вчерашнюю.
    if (size == 2) return ordinal % 2;

    // Дробное деление — «пол» (Dart `~/` усекает к нулю, а дни до 1970-го
    // дают отрицательный порядковый номер: без пола блоки поехали бы).
    final position = ordinal % size;
    final block = (ordinal - position) ~/ size;

    final order = _orderOfBlock(block, size);
    // Стык блоков: первая запись не должна совпасть с последней записью
    // предыдущего блока. Позиция size-1 (size ≥ 3) обменом не затрагивается —
    // рекурсии по истории блоков нет.
    if (order[0] == _orderOfBlock(block - 1, size)[size - 1]) {
      final first = order[0];
      order[0] = order[1];
      order[1] = first;
    }
    return order[position];
  }

  /// Стабильный 32-битный хэш строки (FNV-1a) — одинаков во всех запусках.
  static int stableHash(String value) {
    var hash = 0x811c9dc5;
    for (final unit in value.codeUnits) {
      hash ^= unit;
      hash = (hash * 0x01000193) & 0xffffffff;
    }
    return hash;
  }

  /// Порядковый номер календарного дня от 1970-01-01.
  ///
  /// Считается по UTC-полуночи: счёт дней не должен зависеть от переходов
  /// летнего времени, когда локальные сутки бывают не 24 часа (класс B-17).
  static int _dayOrdinal(DateTime day) =>
      DateTime.utc(day.year, day.month, day.day)
          .difference(DateTime.utc(1970))
          .inDays;

  /// Детерминированная перестановка позиций пула для блока [block].
  static List<int> _orderOfBlock(int block, int size) {
    final order = [for (var i = 0; i < size; i++) i];
    var state = stableHash('block:$block') | 1; // нечётный сид
    for (var i = size - 1; i > 0; i--) {
      state = (state * 1103515245 + 12345) & 0x7fffffff;
      final j = state % (i + 1);
      final carried = order[i];
      order[i] = order[j];
      order[j] = carried;
    }
    return order;
  }
}
