/// Лента контента: окно дней с чтениями + честные пояснения (блок B пакета 7.0).
///
/// Окно короче, чем у ленты событий (7 дней против 30), потому что вопросы
/// разные: события спрашивают «что особенного случится в ближайший месяц»
/// (и их горизонт уведомлений — 60 дней, D-36), а контент ротируется
/// **ежедневно** — показывать полтора месяца вперёд значит показывать один и тот
/// же пул по кругу. Семь дней — «эта неделя», где каждый день уже имеет
/// конкретное чтение.
///
/// Пустая лента — **легальное состояние**, а не ошибка: контент-паков для
/// традиции может не быть вовсе (тексты, прошедшие правовую проверку, собирает
/// человек-трек). Но пустая лента обязана объяснять себя: [notes] несут причины,
/// а [usesFallback] говорит прямо, что показаны собственные формулировки
/// приложения, а не текст традиции (FR-CNT-3, UX-A-4).
library;

import 'content_reading.dart';

/// Результат сборки ленты контента.
class ContentFeed {
  /// Дни окна по возрастанию, без пропусков: и пустой день, и день с фолбэком
  /// присутствуют — «дня нет в ленте» не должно выглядеть как «день без текста».
  final List<DailyReadings> days;

  /// Причины, по которым чего-то нет: по одной строке на состояние, без дублей.
  final List<String> notes;

  const ContentFeed({required this.days, required this.notes});

  /// Пустая лента без пояснений (только для пустого окна).
  static const ContentFeed empty = ContentFeed(days: [], notes: []);

  /// Есть ли хоть одно чтение.
  bool get isEmpty => days.every((d) => d.readings.isEmpty);

  /// Есть ли пояснения (UI показывает плашку честного состояния).
  bool get hasNotes => notes.isNotEmpty;

  /// Показаны ли где-то собственные формулировки приложения вместо контента
  /// традиции — UI обязан сказать об этом, а не выдать фолбэк за текст (FR-CNT-3).
  bool get usesFallback => days.any((d) => d.isFallback);

  /// Все чтения окна в порядке дней.
  List<ContentReading> get allReadings =>
      [for (final day in days) ...day.readings];

  /// Чтения дня [day] (время аргумента не значимо); вне окна — пусто.
  DailyReadings? on(DateTime day) {
    final normalized = DateTime(day.year, day.month, day.day);
    for (final d in days) {
      if (d.date == normalized) return d;
    }
    return null;
  }
}
