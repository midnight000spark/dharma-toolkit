/// Фолбэк-формулировки приложения (FR-CNT-3, P1).
///
/// Когда контент-пака для традиции нет вовсе, «чтение дня» не имеет права
/// превратиться в пустой экран: пользователь получает **собственную краткую
/// формулировку** — текст, который приложение написало само, а не пересказ
/// чужого источника. Требование прямо говорит «собственные», поэтому тексты
/// живут **в коде, а не в ассете**: ассет подразумевал бы «данные традиции», и
/// подмена собственного текста данными — ровно то, что запрещает UX-A-4.
///
/// **Формулировки традиционно-нейтральны.** Универсальный тулкит обслуживает
/// разные традиции, и общий фолбэк обязан подходить всем: ни названий школ, ни
/// терминов конкретной традиции, ни ссылок на тексты, которых у этой традиции
/// нет. Это не «обезличенная вода», а короткое указание к практике, которое
/// честно не выдаёт себя за цитату.
///
/// Честность фолбэка — двойная: [ContentReading.source] помечает его как
/// фолбэк, [ContentReading.isVerified] — `false` (собственный текст не является
/// проверенным текстом традиции), а [attribution] говорит это словами.
library;

import 'content_rotation.dart';

/// Собственные формулировки приложения и их признание в атрибуции.
abstract final class ContentFallbacks {
  /// Заголовок чтения-фолбэка.
  static const String title = 'Короткая практика';

  /// Атрибуция: прямое признание, что это текст приложения, а не традиции.
  static const String attribution =
      'собственная формулировка приложения · контент-пак традиции не установлен';

  /// Пояснение для UI (та же причина, но в терминах состояния экрана).
  static const String note =
      'Контент-пака для активной традиции нет — показана собственная '
      'формулировка приложения (FR-CNT-3).';

  /// Формулировки: короткие, нейтральные, без терминов конкретных традиций.
  static const List<String> formulations = [
    'Подышите ровно: несколько спокойных вдохов и выдохов, без спешки.',
    'Отметьте, что сейчас в теле. Где держится напряжение — отпустите его '
        'на выдохе.',
    'Выберите одно дело сегодня и сделайте его внимательно, а не на '
        'автопилоте.',
    'Вспомните того, кто помог вам сегодня, и мысленно поблагодарите.',
    'Побудьте минуту в тишине: без телефона, без планов, без оценки.',
  ];

  /// Формулировка для дня [day] — той же ротацией, что и чтения из паков:
  /// смена день ото дня без настоящей случайности (детерминизм).
  static String forDay(DateTime day) =>
      formulations[ContentRotation.indexForDay(day, formulations.length)];
}
