/// Фаза Луны по усечённым рядам Мееуса (пакет 5b, блок 2).
///
/// Точность: главные члены гл. 25 (Солнце) и 33 (Луна, ~15 членов долготы,
/// ~5 членов широты) дают геоцентрический элонгационный угол до ~0.1°,
/// т.е. долю фазы до ~0.0003 — на два порядка точнее, чем нужно для
/// определения дня фазы (суточный ход фазы ~0.034).
///
/// Арифметика — `double` осознанно (I-2): источник алгоритма (Мееус) сам
/// опериует тригонометрией конечной точности; точность до дня гарантирована
/// сверкой с тест-векторами astronomia (F-49), а не обещаниями. D-18
/// (Rational) обязательна для расчётного пути Пхугпа; здесь — низкоточный
/// метод с эмпирически подтверждённым допуском.
library;

import 'dart:math' as math;

/// Фаза Луны в момент [g]: `0.0` — новолуние, `0.25` — первая четверть,
/// `0.5` — полнолуние, `0.75` — последняя четверть; диапазон `[0, 1)`.
///
/// Аргумент — григорианский момент (UTC-семантика: поля DateTime interpreted
/// as-is, без пересчёта таймзоны; провайдер передаёт полдень UTC).
double moonPhase(DateTime g) {
  final jd = _toJulianDay(g);
  final t = (jd - 2451545.0) / 36525.0;
  final t2 = t * t;
  final t3 = t2 * t;

  // Солнце: истинная эклиптическая долгота (Meeus ch.25, главные члены).
  final sunMeanLong = _deg(280.46646 + 36000.76983 * t + 0.0003032 * t2);
  final sunMeanAnom =
      _rad(_deg(357.52911 + 35999.05029 * t - 0.0001537 * t2));
  final sunEqCenter = (1.914602 - 0.004817 * t - 0.000014 * t2) *
          math.sin(sunMeanAnom) +
      (0.019993 - 0.000101 * t) * math.sin(2 * sunMeanAnom) +
      0.000289 * math.sin(3 * sunMeanAnom);
  final sunLong = _deg(sunMeanLong + sunEqCenter);

  // Луна: аргументы Мееуса (гл. 33).
  final lp = _deg(218.3164477 +
      481267.88123421 * t -
      0.0015786 * t2 +
      t3 / 538841 -
      t3 * t / 65194000);
  final d = _rad(_deg(297.8501921 +
      445267.1114034 * t -
      0.0018819 * t2 +
      t3 / 545868 -
      t3 * t / 113065000));
  final m = _rad(_deg(357.5291092 +
      35999.0502909 * t -
      0.0001536 * t2 +
      t3 / 24490000));
  final mp = _rad(_deg(134.9633964 +
      477198.8675055 * t +
      0.0087414 * t2 +
      t3 / 69699 -
      t3 * t / 14712000));
  final f = _rad(_deg(93.2720950 +
      483202.0175233 * t -
      0.0036539 * t2 -
      t3 / 3526000 +
      t3 * t / 863310000)); // F (Meeus 33.1) — аргумент рядов долготы
  final fd = _rad(_deg(166.0716130 +
      39.1009021 * t -
      0.0003149 * t2 +
      0.0000104 * t3)); // D′ (Meeus 33.4) — аргумент ряда широты

  // Долгота Луны: 15 главных периодических членов (табл. 33.a).
  final moonLong = _deg(lp +
      6.288774 * math.sin(mp) +
      1.274 * math.sin(2 * d - mp) +
      0.658 * math.sin(2 * d) +
      0.214 * math.sin(2 * mp) -
      0.186 * math.sin(m) -
      0.114 * math.sin(2 * d + mp) -
      0.059 * math.sin(2 * d - 2 * mp) -
      0.057 * math.sin(2 * d - m + mp) +
      0.053 * math.sin(2 * d + mp) +
      0.046 * math.sin(2 * d - m - mp) +
      0.041 * math.sin(m - mp) -
      0.035 * math.sin(3 * d) -
      0.031 * math.sin(m + mp) -
      0.015 * math.sin(2 * f - 2 * mp) +
      0.011 * math.sin(2 * d - 3 * mp));

  // Широта Луны: 5 главных членов (ряды табл. 33.b, аргументы 33.4).
  final moonLat = 5.128 * math.sin(fd) +
      0.281 * math.sin(mp + fd) -
      0.278 * math.sin(fd - mp) +
      0.173 * math.sin(2 * d - fd) +
      0.054 * math.sin(2 * d - mp + fd);

  // Истинный элонгационный угол (сферический, с учётом широты Луны):
  // cos(elong) = cos(beta) * cos(lambda_moon - lambda_sun).
  final dLon = _rad(_deg(moonLong - sunLong));
  final beta = _rad(moonLat);
  var elong = math.acos(math.cos(beta) * math.cos(dLon)); // [0, pi]
  // Восходящая (0..180) против убывающей (180..360) сторона: знак sin(dLon).
  if (math.sin(dLon) < 0) elong = 2 * math.pi - elong;
  return (elong / (2 * math.pi)) % 1.0;
}

/// Нормализация градусов в [0, 360).
double _deg(double x) => x % 360.0;

/// Градусы в радианы.
double _rad(double deg) => deg * math.pi / 180.0;

/// Григорианский момент (по полям DateTime, без пересчёта зоны) в юлианскую
/// дату. Формула Meeus 7.a–7.d (для дат после 15.10.1582). Важно: D —
/// «день + UT/24» без сдвига на полночь; переход от полночи к noon-based
/// шкале JD уже содержит член −1524.5 (вычитание 12 часов дважды сдвигало
/// фазу на полдня — поймано векторами F-49).
double _toJulianDay(DateTime g) {
  var y = g.year;
  var m = g.month;
  if (m <= 2) {
    y -= 1;
    m += 12;
  }
  final a = (y / 100).floor();
  final b = 2 - a + (a / 4).floor();
  final dayFrac = g.day +
      g.hour / 24.0 +
      g.minute / 1440.0 +
      g.second / 86400.0;
  return (365.25 * (y + 4716)).floor() +
      (30.6001 * (m + 1)).floor() +
      dayFrac +
      b -
      1524.5;
}
