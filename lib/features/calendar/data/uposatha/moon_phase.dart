/// Фаза Луны по усечённым рядам Мееуса (пакет 5b, блок 2; сверка — R-24).
///
/// Источник — Meeus, *Astronomical Algorithms*, гл. 25 (Солнце, формулы
/// 25.2–25.4) и гл. 47 (Луна: средние аргументы 47.1–47.5, ряды 47.A и 47.B).
///
/// Точность: 15 главных членов долготы (табл. 47.A) и 5 главных членов
/// широты (табл. 47.B) дают ошибку порядка 0.02° — замерено по собственному
/// примеру книги (Example 47.a, 1992-04-12.0 TD): λ −0.017°, β −0.023° от
/// полного ряда. Это на порядок лучше, чем нужно для определения дня фазы
/// (суточный ход фазы ~0.034, т.е. 1° элонгации ≈ 0.003 фазы).
///
/// Множитель E = 1 − 0.002516T − 0.0000074T² (эксцентриситет земной орбиты)
/// к членам с аргументом M не вводится: для 2024–2026 он равен ≈0.9994, вклад
/// — сотые доли процента членов, т.е. < 1e-5 доли фазы.
///
/// Арифметика — `double` осознанно (I-2): источник алгоритма (Мееус) сам
/// опериует тригонометрией конечной точности; точность до дня гарантирована
/// сверкой с тест-векторами astronomia (F-49), а не обещаниями. D-18
/// (Rational) обязательна для расчётного пути Пхугпа; здесь — низкоточный
/// метод с эмпирически подтверждённым допуском.
library;

import 'dart:math' as math;

/// Фаза Луны в момент [g]: `0.0` — новолуние, `0.25` — первая четверть,
/// `0.5` — полнолуние, `0.75` — последняя четверть; диапазон `[0, 1)`.
///
/// Фаза — истинный геоцентрический элонгационный угол (сферический, с учётом
/// широты Луны [moonEclipticPosition]), а не разность долгот: в новолуние и
/// полнолуние они расходятся на широту Луны (до 5.2°, т.е. до 0.014 доли
/// фазы) — это конвенция величины, а не ошибка ряда.
///
/// Аргумент — григорианский момент **в UTC** (`DateTime.isUtc`): поля DateTime
/// читаются as-is, без пересчёта таймзоны (провайдер передаёт полдень UTC).
/// Локальный момент отклоняется `ArgumentError` — иначе фаза молча сдвинулась
/// бы на смещение зоны (W10).
///
/// Throws [ArgumentError], если [g] не в UTC.
double moonPhase(DateTime g) {
  final jd = _julianDayTt(g);
  final sunLong = _sunLongitude(jd);
  final moon = moonEclipticPosition(g);

  // Истинный элонгационный угол (сферический, с учётом широты Луны):
  // cos(elong) = cos(beta) * cos(lambda_moon - lambda_sun).
  final dLon = _rad(_deg(moon.longitude - sunLong));
  final beta = _rad(moon.latitude);
  var elong = math.acos(math.cos(beta) * math.cos(dLon)); // [0, pi]
  // Восходящая (0..180) против убывающей (180..360) сторона: знак sin(dLon).
  if (math.sin(dLon) < 0) elong = 2 * math.pi - elong;
  return (elong / (2 * math.pi)) % 1.0;
}

/// Истинная эклиптическая долгота Солнца (Meeus гл. 25, главные члены).
double _sunLongitude(double jd) {
  final t = (jd - 2451545.0) / 36525.0;
  final t2 = t * t;
  final sunMeanLong = _deg(280.46646 + 36000.76983 * t + 0.0003032 * t2);
  final sunMeanAnom =
      _rad(_deg(357.52911 + 35999.05029 * t - 0.0001537 * t2));
  final sunEqCenter = (1.914602 - 0.004817 * t - 0.000014 * t2) *
          math.sin(sunMeanAnom) +
      (0.019993 - 0.000101 * t) * math.sin(2 * sunMeanAnom) +
      0.000289 * math.sin(3 * sunMeanAnom);
  return _deg(sunMeanLong + sunEqCenter);
}

/// Геоцентрические эклиптические долгота и широта Луны (градусы) на момент [g].
///
/// Вынесено из [moonPhase] отдельно, чтобы усечённые ряды можно было сверять
/// с первоисточником напрямую — точкой опоры служит собственный пример книги
/// (Meeus, Example 47.a: 1992-04-12.0 TD, JD 2448724.5 → λ = 133.162655°,
/// β = −3.229126°), а не производная величина «фаза» (R-24: тест
/// `moon_phase_meeus_test.dart` ловит искажение любого аргумента ряда).
///
/// Долгота нормализована в `[0, 360)`, широта — в `[−5.3, +5.3]`.
///
/// Аргумент — только UTC (`DateTime.isUtc`), как и у [moonPhase]; локальный
/// момент отклоняется [ArgumentError] (W10).
///
/// Throws [ArgumentError], если [g] не в UTC.
({double longitude, double latitude}) moonEclipticPosition(DateTime g) {
  final jd = _julianDayTt(g);
  final t = (jd - 2451545.0) / 36525.0;
  final t2 = t * t;
  final t3 = t2 * t;

  // Луна: средние аргументы Мееуса (гл. 47, формулы 47.1–47.5).
  final lp = _deg(218.3164477 +
      481267.88123421 * t -
      0.0015786 * t2 +
      t3 / 538841 -
      t3 * t / 65194000);
  final d = _rad(_deg(297.8501921 +
      445267.1114034 * t -
      0.0018819 * t2 +
      t3 / 545868 -
      t3 * t / 113065000));
  final m = _rad(_deg(357.5291092 +
      35999.0502909 * t -
      0.0001536 * t2 +
      t3 / 24490000));
  final mp = _rad(_deg(134.9633964 +
      477198.8675055 * t +
      0.0087414 * t2 +
      t3 / 69699 -
      t3 * t / 14712000));
  // F — аргумент широты Луны (Meeus 47.5). Он же аргумент рядов 47.A и 47.B.
  final f = _rad(_deg(93.2720950 +
      483202.0175233 * t -
      0.0036539 * t2 -
      t3 / 3526000 +
      t3 * t / 863310000));

  // Долгота Луны: 15 главных членов табл. 47.A (аргументы D, M, M', F).
  // R-24: до правки 7 из 15 аргументов/знаков были искажены (в т.ч. `2d+mp`
  // дублировался вместо члена 2F), что давало +0.28° к примеру 47.a.
  final moonLong = _deg(lp +
      6.288774 * math.sin(mp) + // M'
      1.274027 * math.sin(2 * d - mp) + // 2D − M'
      0.658314 * math.sin(2 * d) + // 2D
      0.213618 * math.sin(2 * mp) + // 2M'
      -0.185116 * math.sin(m) + // M
      -0.114332 * math.sin(2 * f) + // 2F
      0.058793 * math.sin(2 * d - 2 * mp) + // 2D − 2M'
      0.057066 * math.sin(2 * d - m - mp) + // 2D − M − M'
      0.053322 * math.sin(2 * d + mp) + // 2D + M'
      0.045758 * math.sin(2 * d - m) + // 2D − M
      -0.040923 * math.sin(m - mp) + // M − M'
      -0.034720 * math.sin(d) + // D
      -0.030383 * math.sin(m + mp) + // M + M'
      0.015327 * math.sin(2 * d - 2 * f) + // 2D − 2F
      -0.012528 * math.sin(mp + 2 * f)); // M' + 2F

  // Широта Луны: 5 главных членов табл. 47.B. Аргумент — F (не «D′»:
  // константа 166.0716°/39.10°/век из прежней версии не соответствует
  // ни одному аргументу гл. 47 и давала β +4.86° к примеру 47.a).
  final moonLat = 5.128122 * math.sin(f) +
      0.280602 * math.sin(mp + f) -
      0.277693 * math.sin(f - mp) +
      0.173237 * math.sin(2 * d - f) +
      0.055413 * math.sin(2 * d - mp + f);

  return (longitude: moonLong, latitude: moonLat);
}

/// Нормализация градусов в [0, 360).
double _deg(double x) => x % 360.0;

/// Градусы в радианы.
double _rad(double deg) => deg * math.pi / 180.0;

/// Контракт момента (W10) и домен дат (S14): все расчёты читают настенные поля
/// DateTime (год/месяц/день/час…), поэтому вход обязан быть UTC
/// (`DateTime.isUtc`), а год — лежать в пролептическом домене `[1, 9999]`.
/// Локальный момент отклоняем громко — молчаливый сдвиг на смещение зоны
/// искажал фазу без единого сигнала; домен объявлен явно, чтобы расхождение
/// двух календарных движков приложения было заявленным, а не случайным.
void _requireUtc(DateTime g) {
  if (!g.isUtc) {
    throw ArgumentError.value(
        g, 'g', 'требуется UTC-момент (DateTime.isUtc) — см. moonPhase');
  }
  if (g.year < 1 || g.year > 9999) {
    throw ArgumentError.value(g, 'g',
        'домен дат — пролептический 0001–9999 (S14); упосатхи — с 1582');
  }
}

/// ΔT = TT − UT, секунды: кусочно-полиномиальная модель Эспенака–Мееуса
/// (NASA GSFC, «Polynomial Expressions for Delta T», 2006) — та же таблица,
/// что в astronomia 4.1.1 (`lib/deltat`), эталоне векторов F-49/S14.
///
/// Таблица заявлена для −1999…+3000; домен приложения шире (0001–9999) и
/// остаётся определённым на нём целиком, но за +3000 работает её же
/// долгосрочная парабола (`−20 + 32u²`, ветка NASA для y ≥ 2150) —
/// экстраполяция на столетия: ≈1.2 ч на 3000 и ≈2.5 сут на 9999, поэтому
/// «день фазы» таких дат гарантий не имеет. В проверенном интервале
/// 1582–2100 расхождение с astronomia — секунды
/// (фикстура `test/fixtures/delta_t_vectors.json`).
///
/// Публична как точка сверки с эталоном (по образцу [julianDayUtc]).
double deltaTSeconds(int year) {
  final y = year.toDouble();
  if (year < -500) {
    final u = (y - 1820) / 100;
    return -20 + 32 * u * u;
  }
  if (year < 500) {
    return _horner(y / 100, const [
      10583.6, -1014.41, 33.78311, -5.952053, -0.1798452, 0.022174192,
      0.0090316521,
    ]);
  }
  if (year < 1600) {
    return _horner((y - 1000) / 100, const [
      1574.2, -556.01, 71.23472, 0.319781, -0.8503463, -0.005050998,
      0.0083572073,
    ]);
  }
  if (year < 1700) {
    return _horner(y - 1600, const [120, -0.9808, -0.01532, 1 / 7129]);
  }
  if (year < 1800) {
    return _horner(
        y - 1700, const [8.83, 0.1603, -0.0059285, 0.00013336, -1 / 1174000]);
  }
  if (year < 1860) {
    return _horner(y - 1800, const [
      13.72, -0.332447, 0.0068612, 0.0041116, -0.00037436, 0.0000121272,
      -0.0000001699, 0.000000000875,
    ]);
  }
  if (year < 1900) {
    return _horner(y - 1860,
        const [7.62, 0.5737, -0.251754, 0.01680668, -0.0004473624, 1 / 233174]);
  }
  if (year < 1920) {
    return _horner(
        y - 1900, const [-2.79, 1.494119, -0.0598939, 0.0061966, -0.000197]);
  }
  if (year < 1941) {
    return _horner(y - 1920, const [21.20, 0.84493, -0.076100, 0.0020936]);
  }
  if (year < 1961) {
    return _horner(y - 1950, const [29.07, 0.407, -1 / 233, 1 / 2547]);
  }
  if (year < 1986) {
    return _horner(y - 1975, const [45.45, 1.067, -1 / 260, -1 / 718]);
  }
  if (year < 2005) {
    return _horner(y - 2000, const [
      63.86, 0.3345, -0.060374, 0.0017275, 0.000651814, 0.00002373599,
    ]);
  }
  if (year < 2050) {
    return _horner(y - 2000, const [62.92, 0.32217, 0.005589]);
  }
  final u = (y - 1820) / 100;
  // 2050–2150 — переходная ветка NASA; ≥2150 — та же парабола без поправки.
  return year < 2150
      ? _horner(u, const [-205.72, 56.28, 32])
      : -20 + 32 * u * u;
}

/// Схема Горнера для коэффициентов по возрастанию степени: c₀ + c₁x + … .
double _horner(double x, List<double> c) {
  var result = 0.0;
  for (var i = c.length - 1; i >= 0; i--) {
    result = result * x + c[i];
  }
  return result;
}

/// Юлианская дата (UT) по полям UTC-момента [g]: Meeus 7.a–7.d **с веткой
/// реформы 1582-10-15**. До реформы действует юлианский календарь (b = 0),
/// после — григорианская поправка `b = 2 − a + ⌊a/4⌋`; без ветки даты до
/// 1582-10-15 уезжали бы на дни (находка S14). Публична как точка сверки с
/// эталоном astronomia (`CalendarJulianToJD`/`CalendarGregorianToJD`), по
/// образцу [moonEclipticPosition]; ΔT не включает — шкала UT.
///
/// Важно: D — «день + UT/24» без сдвига на полночь; переход от полночи к
/// noon-based шкале JD уже содержит член −1524.5 (вычитание 12 часов дважды
/// сдвигало фазу на полдня — поймано векторами F-49).
double julianDayUtc(DateTime g) {
  _requireUtc(g);
  var y = g.year;
  var m = g.month;
  if (m <= 2) {
    y -= 1;
    m += 12;
  }
  final int b;
  if (g.year * 10000 + g.month * 100 + g.day < 15821015) {
    b = 0; // юлианский календарь до реформы (Meeus 7.a)
  } else {
    final a = (y / 100).floor();
    b = 2 - a + (a / 4).floor();
  }
  final dayFrac = g.day +
      g.hour / 24.0 +
      g.minute / 1440.0 +
      g.second / 86400.0;
  return (365.25 * (y + 4716)).floor() +
      (30.6001 * (m + 1)).floor() +
      dayFrac +
      b -
      1524.5;
}

/// Юлианская дата в шкале TT для рядов Мееуса: JDE = JD (UT) + ΔT/86400.
/// Ряды гл. 25/47 отдают положение на момент T в TT; без этого члена
/// систематический сдвиг ~69 с для 2024 (S14).
double _julianDayTt(DateTime g) =>
    julianDayUtc(g) + deltaTSeconds(g.year) / 86400.0;
