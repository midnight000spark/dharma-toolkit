/// Абстракция календаря традиции (FR-CAL-1).
///
/// Модуль календаря и UI зависят от этого интерфейса, а не от конкретных
/// реализаций (тибетского порта или лунной арифметики) — изоляция R-3.
///
/// Реализации:
///  * `TibetanCalendarProvider` — дни 10/25 и праздники Пхугпа (FR-CAL-3);
///  * `UposathaCalendarProvider` — упосатхи по фазам Луны (FR-CAL-2).
///
/// Архитектурная заметка (I-3, D-30): интерфейс спроектирован для
/// параметризации — будущий `BonCalendarProvider` использует тот же
/// вычислительный движок Пхугпа с другими конвенциями и собственным паком
/// праздников (F-47: математика идентична, отличаются имена лет, старт
/// цикла и паки дат; F-48: «переключателя года» недостаточно). Никаких
/// изменений в интерфейсе для этого не требуется: бонские даты — это
/// [SpecialDay] с [SpecialDayType.festival] и своими именами.
library;

import 'special_day.dart';

/// Календарь одной традиции: знает свой [traditionTag] и отдаёт особые дни
/// на григорианском диапазоне.
abstract class CalendarProvider {
  /// Тег традиции для изоляции данных (принцип №3): значение приходит из
  /// активного пресета (`preset.id`: 'nyingma', 'theravada_default';
  /// будущее: 'bon'), в коде не захардкодится (B-4).
  String get traditionTag;

  /// Особые дни в диапазоне [from]..[to] включительно (григорианские даты;
  /// время в аргументах не значимо).
  ///
  /// Контракт реализации:
  ///  * результат отсортирован по возрастанию [SpecialDay.date];
  ///  * все даты результата лежат в диапазоне (границы включаются);
  ///  * один календарный день может иметь несколько особых дней разных
  ///    типов (например, праздник на 10-м дне) — дубли по (date, type)
  ///    недопустимы;
  ///  * метод чистый: не мигрирует состояние, один и тот же диапазон даёт
  ///    один и тот же результат; пустой список вместо null;
  ///  * бросает исключение только при некорректных аргументах
  ///    (from после to), не при пустом результате.
  List<SpecialDay> getSpecialDays(DateTime from, DateTime to);
}
