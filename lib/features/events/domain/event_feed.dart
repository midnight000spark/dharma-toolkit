/// Лента событий: отсортированные записи + честные сообщения о том, чего в ней
/// нет и почему (блок C пакета 6.1).
///
/// Пустая лента — **легальное состояние**, а не ошибка: у традиции может не быть
/// особых дней в окне, а паки могут ещё не быть собраны (проверенные даты
/// собирает человек-трек). Но пустая лента обязана уметь объяснить себя:
/// [notes] несут причины («календаря для традиции нет», «пак не подтверждён»,
/// «правило tibetan неразрешимо»), чтобы UI показывал осмысленное состояние
/// (SCR-12), а не молчаливую пустоту.
library;

import 'feed_entry.dart';

/// Результат слияния календаря и паков событий.
class EventFeed {
  /// Записи, отсортированные по дате (затем: календарь → пак; затем название).
  final List<FeedEntry> entries;

  /// Причины, по которым чего-то нет: по одной строке на состояние, без дублей.
  final List<String> notes;

  const EventFeed({required this.entries, required this.notes});

  /// Пустая лента без пояснений (только для пустого входа без деградаций).
  static const EventFeed empty = EventFeed(entries: [], notes: []);

  /// Есть ли записи.
  bool get isEmpty => entries.isEmpty;

  /// Есть ли пояснения (UI показывает плашку честного состояния).
  bool get hasNotes => notes.isNotEmpty;

  /// Записи конкретного календарного дня (время аргумента не значимо).
  List<FeedEntry> on(DateTime day) {
    final normalized = DateTime(day.year, day.month, day.day);
    return [
      for (final e in entries)
        if (e.date == normalized) e,
    ];
  }
}
